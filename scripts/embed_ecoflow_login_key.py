#!/usr/bin/env python3
"""Embed third_party/ecoflow/login_key.bin into EcoFlowLoginKeyData.gen.cpp.

The bin is the public EcoFlow app login-key table (not account credentials).
See third_party/ecoflow/README.md.
"""

from __future__ import annotations

import sys
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
src_bin = repo / "third_party" / "ecoflow" / "login_key.bin"
out_cpp = (
    repo
    / "src"
    / "bridge_ecoflow_delta3"
    / "EcoFlow"
    / "Crypto"
    / "EcoFlowLoginKeyData.gen.cpp"
)
EXPECTED = 65280


def write_gen(data: bytes) -> None:
    body_lines = [f"const uint8_t kEcoFlowLoginKey[{len(data)}] = {{"]
    per_line = 256
    for i in range(0, len(data), per_line):
        chunk = data[i : i + per_line]
        hex_body = ",".join(f"0x{b:02x}" for b in chunk)
        suffix = "," if i + per_line < len(data) else ""
        body_lines.append(f"  {hex_body}{suffix}")
    body_lines += [
        "};",
        "",
        f"const size_t kEcoFlowLoginKeySize = {len(data)};",
    ]
    text = "\n".join(
        [
            "// AUTO-GENERATED by scripts/embed_ecoflow_login_key.py — do not commit.",
            '#include "EcoFlow/Crypto/EcoFlowLoginKey.h"',
            "",
            "namespace ecoflow::crypto {",
            "",
            *body_lines,
            "",
            "}  // namespace ecoflow::crypto",
            "",
        ]
    )
    out_cpp.write_text(text, encoding="utf-8", newline="\n")
    print(f"Embedded EcoFlow login key ({len(data)} bytes) -> {out_cpp.relative_to(repo)}")


def main() -> int:
    if not src_bin.is_file():
        print(
            f"Missing {src_bin.relative_to(repo)} — public table must be present "
            "(see third_party/ecoflow/README.md; regenerate from "
            "https://github.com/rabits/ef-ble-reverse util/login_key_gen.py)",
            file=sys.stderr,
        )
        return 1

    data = src_bin.read_bytes()
    if len(data) != EXPECTED:
        print(f"login_key.bin size {len(data)} != {EXPECTED}", file=sys.stderr)
        return 1

    if out_cpp.is_file() and out_cpp.stat().st_mtime >= src_bin.stat().st_mtime:
        print(f"EcoFlow login key embed up to date ({len(data)} bytes)")
        return 0

    write_gen(data)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
